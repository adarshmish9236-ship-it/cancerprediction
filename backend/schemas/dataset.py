"""
CANCERWISE AI — Dataset Schemas & Models
Pydantic data models for dataset metadata, validation, and ingestion.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class DataModality(str, Enum):
    """Supported data modalities."""
    TABULAR = "TABULAR"
    IMAGE = "IMAGE"
    GENOMIC = "GENOMIC"
    MULTIMODAL = "MULTIMODAL"


class DataFormat(str, Enum):
    """Supported file/data formats."""
    CSV = "CSV"
    PARQUET = "PARQUET"
    XLSX = "XLSX"
    JSON = "JSON"
    IMAGE_DIRECTORY = "IMAGE_DIRECTORY"
    DICOM = "DICOM"
    FASTA = "FASTA"
    VCF = "VCF"


class TargetType(str, Enum):
    """Types of machine learning targets."""
    BINARY_CLASSIFICATION = "BINARY_CLASSIFICATION"
    MULTICLASS_CLASSIFICATION = "MULTICLASS_CLASSIFICATION"
    REGRESSION = "REGRESSION"
    SURVIVAL_ANALYSIS = "SURVIVAL_ANALYSIS"
    UNSUPERVISED = "UNSUPERVISED"


class DatasetColumnInfo(BaseModel):
    """Metadata for a single column/feature."""
    name: str
    dtype: str
    null_count: int = 0
    null_percentage: float = 0.0
    unique_count: int = 0
    is_target: bool = False
    is_identifier: bool = False
    clinical_unit: Optional[str] = None
    description: Optional[str] = None


class DatasetStatisticsSummary(BaseModel):
    """Statistical summary of a dataset."""
    records_count: int
    columns_count: int
    memory_usage_mb: float
    duplicate_rows_count: int
    total_missing_values: int
    missing_percentage: float
    target_distribution: Optional[Dict[str, int]] = None
    target_percentages: Optional[Dict[str, float]] = None
    numeric_feature_count: int
    categorical_feature_count: int
    columns: List[DatasetColumnInfo] = Field(default_factory=list)


class DatasetMetadata(BaseModel):
    """
    Standardized metadata record for any dataset in CANCERWISE AI.
    """
    dataset_id: str
    name: str
    description: str
    original_source: str
    source_url: Optional[str] = None
    download_timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    license: str
    records_count: int
    columns_count: int
    target_variable: Optional[str] = None
    target_classes: Optional[List[str]] = None
    target_type: TargetType = TargetType.BINARY_CLASSIFICATION
    feature_names: List[str] = Field(default_factory=list)
    missing_values_count: int = 0
    modality: DataModality = DataModality.TABULAR
    data_format: DataFormat = DataFormat.CSV
    version: str = "1.0.0"
    sha256_checksum: str
    raw_file_path: str
    processed_file_path: Optional[str] = None
    provenance: Dict[str, Any] = Field(default_factory=dict)
    schema_definition: Dict[str, str] = Field(default_factory=dict)

    @property
    def created_at(self) -> str:
        return self.download_timestamp


class DatasetValidationReport(BaseModel):
    """Report generated by DatasetValidator."""
    dataset_id: str
    is_valid: bool
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
    total_checks: int
    passed_checks: int
    failed_checks: int
    errors: List[str] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    integrity_verified: bool
    checksum_matched: bool
    summary: Dict[str, Any] = Field(default_factory=dict)


class SchemaCompatibilityReport(BaseModel):
    """Report evaluating compatibility between two datasets before potential integration."""
    dataset_a_id: str
    dataset_b_id: str
    compatible: bool
    modality_match: bool
    reasons: List[str] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    shared_features: List[str] = Field(default_factory=list)
    disjoint_features_a: List[str] = Field(default_factory=list)
    disjoint_features_b: List[str] = Field(default_factory=list)
    type_mismatches: Dict[str, Dict[str, str]] = Field(default_factory=dict)
    unit_mismatches: Dict[str, Dict[str, str]] = Field(default_factory=dict)
    label_compatibility: Optional[str] = None


class DatasetPreview(BaseModel):
    """Preview slice and summary for API / UI display."""
    dataset_id: str
    name: str
    shape: List[int]
    columns: List[str]
    dtypes: Dict[str, str]
    head: List[Dict[str, Any]]
    tail: List[Dict[str, Any]]
    target_distribution: Optional[Dict[str, int]] = None
